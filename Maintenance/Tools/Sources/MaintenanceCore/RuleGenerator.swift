import Foundation

struct GeneratedRuleFiles {
  let contentsByPath: [String: Data]

  var count: Int {
    contentsByPath.count
  }
}

enum RuleGenerator {
  static func run(
    project: MaintenanceProject,
    outputRoot: URL
  ) throws -> GeneratedRuleFiles {
    let generated = try makeFiles(project: project)
    for path in MaintenanceProject.generatedSourcePaths {
      guard let contents = generated.contentsByPath[path] else {
        throw MaintenanceError("rule generator omitted expected output: \(path)")
      }
      try FileSystem.write(contents, to: relativeURL(path, under: outputRoot))
    }
    return generated
  }

  static func makeFiles(project: MaintenanceProject) throws -> GeneratedRuleFiles {
    try verifyRuleModel(project)
    let defaultEnablement = try loadDefaultEnablement(project)

    let pipeline = makePipeline(rules: project.rules)
    let registry = try makeRegistry(
      rules: project.rules,
      defaultEnablement: defaultEnablement
    )
    let nameCache = makeNameCache(rules: project.rules)

    return GeneratedRuleFiles(
      contentsByPath: [
        "Sources/SwiftFormat/Core/Pipelines+Generated.swift": Data(pipeline.utf8),
        "Sources/SwiftFormat/Core/RuleNameCache+Generated.swift": Data(nameCache.utf8),
        "Sources/SwiftFormat/Core/RuleRegistry+Generated.swift": Data(registry.utf8),
      ]
    )
  }

  static func verifyRuleModel(_ project: MaintenanceProject) throws {
    let upstreamPipeline = try project.upstreamText(
      path: "Sources/SwiftFormat/Core/Pipelines+Generated.swift"
    )
    let pipelineRules = try regexCaptures(
      pattern: #"node = ([A-Za-z0-9]+)\(context: context\)"#,
      in: upstreamPipeline
    ).compactMap(\.first)
    try require(
      pipelineRules == project.rules,
      "rules.txt does not exactly match the ordered "
        + "\(project.lock.swiftFormatTag) formatter pipeline"
    )

    let retainedTestDestinations = Set(project.suiteSources.map(\.destination))
    for rule in project.rules {
      let sourcePath = ruleSourcePath(rule)
      let sourceText: String
      do {
        sourceText = try project.upstreamText(path: sourcePath)
      } catch {
        throw MaintenanceError("missing formatter rule source: \(sourcePath)")
      }
      try require(
        sourceText.contains("class \(rule): SyntaxFormatRule"),
        "rule is not a SyntaxFormatRule in the pinned upstream release: \(rule)"
      )

      let testPath = ruleTestPath(rule)
      try require(
        retainedTestDestinations.contains(testPath),
        "missing retained formatter rule test snapshot: \(testPath)"
      )
    }
  }

  private static func loadDefaultEnablement(
    _ project: MaintenanceProject
  ) throws -> [String: Bool] {
    let registry = try project.upstreamText(
      path: "Sources/SwiftFormat/Core/RuleRegistry+Generated.swift"
    )
    let lines = registry.split(separator: "\n", omittingEmptySubsequences: false)
    var result: [String: Bool] = [:]

    for rule in project.rules {
      let prefix = "\"\(rule)\": "
      let matches = lines.compactMap { rawLine -> Bool? in
        let line = rawLine.trimmingCharacters(in: .whitespaces)
        guard line.hasPrefix(prefix), line.hasSuffix(",") else {
          return nil
        }
        let valueStart = line.index(line.startIndex, offsetBy: prefix.count)
        let value = String(line[valueStart...].dropLast())
        switch value {
        case "true":
          return true
        case "false":
          return false
        default:
          return nil
        }
      }
      try require(
        matches.count == 1,
        "cannot determine upstream default enablement for \(rule)"
      )
      result[rule] = matches[0]
    }

    return result
  }

  private static func makePipeline(rules: [String]) -> String {
    var lines = [
      "// Generated by Maintenance/generate-rules. Do not edit.",
      "import SwiftSyntax",
      "extension FormatPipeline {",
      "  func rewrite(_ node: Syntax) -> Syntax {",
      "    var node = node",
    ]
    lines.append(
      contentsOf: rules.map {
        "    node = \($0)(context: context).rewrite(node)"
      })
    lines.append(contentsOf: [
      "    return node",
      "  }",
      "}",
    ])
    return lines.joined(separator: "\n") + "\n"
  }

  private static func makeRegistry(
    rules: [String],
    defaultEnablement: [String: Bool]
  ) throws -> String {
    var lines = [
      "// Generated by Maintenance/generate-rules. Do not edit.",
      "@_spi(Internal) public enum RuleRegistry {",
      "  public static let rules: [String: Bool] = [",
    ]
    for rule in rules {
      guard let enabled = defaultEnablement[rule] else {
        throw MaintenanceError("missing default enablement for \(rule)")
      }
      lines.append("    \"\(rule)\": \(enabled),")
    }
    lines.append(contentsOf: [
      "  ]",
      "}",
    ])
    return lines.joined(separator: "\n") + "\n"
  }

  private static func makeNameCache(rules: [String]) -> String {
    var lines = [
      "// Generated by Maintenance/generate-rules. Do not edit.",
      "@_spi(Testing) public let ruleNameCache: [ObjectIdentifier: String] = [",
    ]
    lines.append(
      contentsOf: rules.map {
        "  ObjectIdentifier(\($0).self): \"\($0)\","
      })
    lines.append("]")
    return lines.joined(separator: "\n") + "\n"
  }
}

public enum GenerateRulesTool {
  public static func run(projectRoot: URL, outputRoot: URL) throws {
    let project = try MaintenanceProject.load(root: projectRoot)
    try EnvironmentVerifier.verify(project)
    let generated = try RuleGenerator.run(
      project: project,
      outputRoot: outputRoot
    )
    print(
      "generate-rules: wrote \(generated.count) files for "
        + "\(project.rules.count) formatter rules at \(outputRoot.path)"
    )
  }
}
